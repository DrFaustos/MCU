"""MCU — кроссплатформенный ВКС: сервер (комната+микшеры+/admin) и терминал (набор/приём)."""

# Вариант сборки = линия ветки, из которой собран клиент: «h323» — ветка
# с полным H.323-стеком (мосты к хосту mcu_h323d), «sip» — SIP-линейка.
# Это свойство ИСХОДНИКОВ, а не флаг сборки: тег релиза обязан кончаться
# на этот же суффикс (проверка в .github/workflows/release.yml), иначе
# тег v0.2.34-sip, поставленный на h323-коммит, соберёт «sip»- exe, в
# котором на самом деле h323-код, и никакое имя артефакта не спасёт.
PROTOCOL_VARIANT = "h323"

__version__ = "0.3.8"


def version_string() -> str:
    """Строка версии, совпадающая с тегом релиза: 0.2.34-h323."""
    return f"{__version__}-{PROTOCOL_VARIANT}"


__all__ = ["PROTOCOL_VARIANT", "__version__", "version_string"]
