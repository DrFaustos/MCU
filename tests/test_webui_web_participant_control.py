"""Панель обязана управлять ЧУЖИМИ веб-участниками: сервер умел, кнопок не было.

Воспроизведено 2026-10-21 в ветке h323. Инвентаризация маршрутов (приём,
закрытый мёртвыми /api/webrtc/close, POST /api/dtmf и выбором микрофона) оставила
два мёртвых маршрута с реальным операторским смыслом: GET-дубли разобраны, а
POST /api/conference/media и /api/conference/rename — это мьют, камера и имя
конкретного браузера в комнате. Сервер их обслуживал с самого начала, док
обещал, ядро умело.

Срез шёл ПОСЛЕ 2502795 («управление веб-участником — 404/400 с причиной»)
сознательно: кнопка, добавленная до правки отказа, унаследовала бы молчаливое
ok:false — тот же порядок, что с микрофонами.

Ловушка, из-за которой этот файл существует почти целиком. Обработчик кликов по
тайлам один на всех и начинался с `const id = Number(btn.dataset.id)`. У SIP-
участника id числовой, у веб-участника — строка `web-1`:

    Number("web-1") -> NaN -> JSON `{"id": null}` -> HTTP 400

(замерено: node даёт NaN, сервер на null и на "web-1" отвечает 400 «Некорректный
participant id»). Механическая дописка web-кнопки в ту же карту дала бы кнопку,
которая всегда отказывает, и зелёные тесты этого не увидели бы: они проверяли бы
карту, а не тип id. Отсюда проверки на то, что строковый id веб-участника доходит
до сервера строкой.

Проверки по исходнику: браузера в тестовой среде нет, приём тот же, что в
tests/test_webui_audio_device_panel.py и tests/test_panel_failure_refresh.py.
"""

from __future__ import annotations

import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]
WEBUI = ROOT / "mcuclient" / "webui"

#: Действия на тайле веб-участника: имя действия -> маршрут, которому оно
#: принадлежит. Сверяется с EXEMPT_ROUTES в test_webui_audio_device_panel.py:
#: как только кнопка появилась, маршрут обязан покинуть allow-list.
WEB_ROUTES = ("/conference/media", "/conference/rename")


def _html() -> str:
    return (WEBUI / "index.html").read_text(encoding="utf-8")


def _code_only(text: str) -> str:
    """Текст без JS-комментариев; порядок срезов — см. урок в _js() ниже."""
    text = re.sub(r"(?<!:)//[^\n]*", "", text)
    return re.sub(r"/\*.*?\*/", " ", text, flags=re.S)


def _js() -> str:
    parts = re.findall(r"<script>(.*?)</script>", _html(), flags=re.S)
    parts.append((WEBUI / "ms-conference.js").read_text(encoding="utf-8"))
    return _code_only("\n".join(parts))


def _web_tile_branch() -> str:
    """Кусок renderTiles, рисующий тайл веб-участника (ветка `if (p.web)`)."""
    js = _js()
    at = js.index("if (p.web)")
    # Ветка кончается возвратом шаблона: ищем закрывающий обратный штрих-тиль
    # последнего return-литерала ветки.
    end = js.index("`;", at)
    return js[at:end + 2]


def _grid_click_handler() -> str:
    """Тело обработчика кликов по сетке тайлов (делегирование на `$('grid')`)."""
    js = _js()
    at = js.index("$('grid').addEventListener('click'")
    tail = js[at:]
    # Обработчик заканчивается строкой `});` на нулевом отступе — ближайшая.
    m = re.search(r"^\}\);", tail, flags=re.M)
    assert m, "не нашлось конца обработчика кликов по тайлам"
    return tail[:m.end()]


# --- главное: маршруты живые ------------------------------------------------


def test_panel_calls_web_control_routes():
    """Мьют/камера/имя веб-участника обязаны вызываться из панели.

    До правки — ноль совпадений по обоим путям при полностью готовом сервере.
    """
    js = _js()
    for route in WEB_ROUTES:
        assert route in js, (
            f"панель не зовёт POST /api{route}: оператор из браузера не может "
            "управлять веб-участником, хотя сервер умеет и отказывает честно")


