def test_handler_uses_raw_status_fields():
    """Обработчик кликов обязан читать СЫРЫЕ поля статуса, а не поля маппинга.

    Поймано на собственной правке этого же среза, до первого прогона.
    `renderTiles` строит локальный маппинг (`muted: !p.audio_enabled`,
    `label: p.name`) — он виден ТОЛЬКО внутри этой функции. Обработчик кликов
    живёт отдельно и обязан брать `audio_enabled` / `video_enabled` / `name` из
    `webParticipants` напрямую.

    Цена ошибки — вечно неверное состояние: первой версии достаточно было
    `!!web.muted`, где `web` — элемент `webParticipants`, а такого поля у него
    нет. `undefined` дал бы «включить звук» на включённом звуке, т.е. кнопка
    врёт о состоянии ДО всякого запроса, и выглядит это как сломанный МСУ, а не
    как опечатка в имени поля.
    """
    handler = _grid_click_handler()
    assert re.search(r"\b(audio_enabled|video_enabled)\b", handler), (
        "обработчик кликов не читает audio_enabled/video_enabled из статуса: "
        "состояние веб-участника берётся из поля, которого у него нет")
    assert not re.search(r"!!\s*web\.(muted|video_muted|label)\b", handler), (
        "обработчик читает поля локального маппинга renderTiles (muted/"
        "video_muted/label) — досюда они не видны, состояние всегда undefined")


