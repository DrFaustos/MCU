def test_web_tile_can_remove_a_participant():
    """Оператор обязан иметь чем убрать зависший браузер.

    Тот же класс дыры, что закрыт выше: сервер готов, кнопок нет. Замер
    2026-10-21: `conference_leave` принимает ЛЮБОЙ id — выход чужого вернул
    `{'ok': True}`, и `web-2` исчез из комнаты. При этом на чужом веб-тайле не
    было ни одной кнопки выхода, а у SIP-тайла «Сброс» есть.

    Почему это нужно именно в веб-тайле (а не «доделали state»). Срез F научил
    панель выводить СЕБЯ при закрытии вкладки, но при обрыве сети beacon не
    уходит в принципе; `state` веб-участника при этом о живости не сообщает
    ничего (его не обновляет никто, вечно `connected`). Единственное средство,
    доступное оператору с МСУ прямо сейчас, — кнопка.
    """
    branch = _web_tile_branch()
    assert 'data-act="wkick"' in branch, (
        "на чужом веб-тайле нет кнопки удаления: зависший после обрыва браузер "
        "невозможно убрать из комнаты, хотя сервер это умеет")


