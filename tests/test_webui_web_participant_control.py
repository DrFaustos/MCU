def test_kick_button_follows_the_destructive_convention():
    """Необратимое действие обязано выглядеть необратимым.

    `confirm(` в этой панели нет НИ ОДНОГО — при этом деструктивный сброс
    SIP-вызова сделан `class="danger" data-act="hangup"`. Конвенция уже
    существует, и изобретать второй стиль (диалог подтверждения) дороже: он
    оторвал бы кнопку от остальных. Проверяется метка danger на самой кнопке,
    а не «danger встречается где-то в ветке»: иначе её обеспечил бы чужой
    элемент, и проверка стала бы мёртвой.
    """
    branch = _web_tile_branch()
    at = branch.index('data-act="wkick"')
    tag = branch.rfind("<button", 0, at)
    assert tag >= 0 and 'class="danger"' in branch[tag:at], (
        "кнопка удаления не помечена danger: необратимое действие неотличимо "
        "от «Мут» — та же конвенция, что у SIP-сброса")


def test_kick_goes_through_the_shared_action_map():
    """Действие обязано идти через `act(map[action])`, а не прямым `api(...)`.

    Сетка перерисовывается `refresh()`-ом внутри `act()`. Прямой вызов оставил
    бы удалённый тайл висеть до следующего тика (3 с) — оператор жмёт ещё раз,
    получает `ok: false` и решает, что кнопка не работает. Существующая проверка
    `test_web_actions_go_through_act` видит лишь наличие `act(` в обработчике и
    на одной кнопке вне map бы не покраснела; здесь сверяется ПОЗИЦИЯ wkick
    внутри объявления карты и сам вызов.
    """
    handler = _grid_click_handler()
    at_map = handler.index("const map = {")
    assert handler.index("wkick") > at_map, (
        "wkick объявлен вне карты действий — его вызов обязан проходить через "
        "act(map[action]), иначе отказ невидим и сетка не обновится")
    assert "act(map[action])" in handler, (
        "обработчик больше не вызывает act(map[action]): удалённый участник "
        "продолжал бы висеть в сетке до следующего тика опроса")
