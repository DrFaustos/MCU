#!/usr/bin/env bash
# Общие проверки для стендовых обёрток (scripts/testbed/run_two_instance_*.sh).
#
# Зачем. Раньше обёртки решали об успехе ТОЛЬКО по коду возврата python-раннера,
# а раннеры при недоступном pjsua2 печатают «[skip] pjsua2 недоступен» и
# возвращают 0 (что верно для pytest/skipif, но не для обёртки). Результат —
# ложноположительный зелёный, воспроизведённый живьём:
#
#   $ bash scripts/testbed/run_two_instance_test.sh
#   [skip] pjsua2 недоступен
#   [+] MCU<->MCU OK          <-- хотя SIP-стека не было вовсе
#
# Поэтому обёртка обязана: (а) проверить стек ДО запуска, (б) не объявлять
# успех, если в логе есть [skip], (в) требовать маркер успеха в логе.
#
# Коды возврата: 0 — стенд прошёл; 1 — стенд упал; 2 — стенд НЕ ВЫПОЛНЯЛСЯ
# (нет стека/интерпретатора). 2 отделён от 1 намеренно и совпадает с
# run_local_sip_testbed.sh, где 2 = «не найден asterisk/sipp». Тишина вместо
# «не запускалось» — это и был исходный баг.

# Резолв интерпретатора: PYTHON из окружения, иначе python3.
stand_python() {
  printf '%s' "${PYTHON:-python3}"
}

# Есть ли pjsua2 в указанном интерпретаторе. Не печатает: используется в условиях.
stand_has_pjsua2() {
  local py="${1:-python3}"
  command -v "$py" >/dev/null 2>&1 || return 2
  "$py" -c "import pjsua2" >/dev/null 2>&1
}

# Стоп-проверка перед прогоном: без нативного стека стенд бессмыслен, и
# молча «зелёным» он быть не должен.
stand_require_pjsua2() {
  local py="$1" what="${2:-стенд}"
  if ! command -v "$py" >/dev/null 2>&1; then
    echo "[!] интерпретатор '$py' не найден — укажите PYTHON=/path/to/python" >&2
    return 2
  fi
  if ! stand_has_pjsua2 "$py"; then
    {
      echo "[!] $what не выполнялся: в '$py' нет pjsua2."
      echo "    SIP-раннер при отсутствии стека печатает [skip] и возвращает 0,"
      echo "    поэтому обёртка обязана остановить прогон здесь, а не рапортовать OK."
      echo "    Боевой интерпретатор этого ноутбука: PYTHON=/usr/bin/python3 $0"
      echo "    (установка: scripts/install_pjsua2.sh)"
    } >&2
    return 2
  fi
  return 0
}

# Был ли пропуск: [skip] в логе = раннер ничего не проверял.
stand_skip_seen() {
  local log="$1"
  [ -f "$log" ] && grep -q '\[skip\]' "$log"
}

# Объявить пропуск одинаково во всех обёртках и выйти с 2 (не с 0!).
# Логи передают ВСЕ: [skip] мог появиться только на одном конце, а печатать
# нужно именно найденные строки — иначе «почему не запускалось» теряется.
stand_report_skip() {
  local log
  echo "[!] стенд НЕ ВЫПОЛНЯЛСЯ: в логах есть [skip] — раннер ничего не проверял:" >&2
  for log in "$@"; do
    [ -f "$log" ] && grep '\[skip\]' "$log" | sort -u | sed 's/^/    /' >&2
  done
  return 2
}

# Единственный стенд за раз. Проверено живьём: два параллельных прогона
# мешают друг другу — DTMF теряет тоны («1984#» превращается в «184#»), а
# чат-стенд ловит нативный abort pjsua2
# (`grp_lock_acquire: Assertion ... failed`, core dumped). Падать при этом
# молча — значит подменять дефект окружения дефектом кода: агент чинит
# движок, которого не касался. Отсюда честный rc=2 «не выполнялся».
#
# Механизм — flock на fd 9. Дочерние процессы наследуют fd и держат замок,
# пока живы; обёртки ждут слушателя через `wait`, поэтому к моменту выхода
# обёртки замок свободен. Если обёртку убить извне (timeout), сирота-слушатель
# продолжает держать замок — и это верно: он реально занимает порты стенда.
stand_gate() {
  local what="${1:-стенд}"
  local lock="${MCU_STAND_LOCK:-/tmp/mcu-testbed.lock}"
  command -v flock >/dev/null 2>&1 || return 0   # нет util-linux — не мешаем
  # Проверка каталога обязательна: в неинтерактивном bash ошибка редиректа у
  # special builtin `exec` завершает оболочку. Без проверки обёртка при
  # недоступном MCU_STAND_LOCK умерла бы молча — ровно тот баг (тишина вместо
  # «не запускалось»), против которого этот замок и поставлен.
  local dir
  dir="$(dirname "$lock")"
  [ -d "$dir" ] && [ -w "$dir" ] || return 0
  exec 9>"$lock" || return 0
  if flock -n 9; then
    return 0
  fi
  {
    echo "[!] $what: стенд НЕ ВЫПОЛНЯЛСЯ — уже идёт другой стендовый прогон"
    echo "    (замок $lock). Стенды MCU делят живые SIP-порты и тайминги RTP,"
    echo "    поэтому запускаются СТРОГО ПОСЛЕДОВАТЕЛЬНО: дождитесь окончания"
    echo "    предыдущего либо укажите свой MCU_STAND_LOCK для параллельного"
    echo "    прогона, если точно знаете, что порты не пересекаются."
  } >&2
  return 2
}
